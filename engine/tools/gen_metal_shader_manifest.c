/* Plan C Task 10: manifest generator for the offline Metal shader pipeline.
 *
 * Reads <manifest.lines> (rows: "<glsl_basename> <msl_entry>") produced by
 * compile_metal_shaders.sh, hashes each original GLSL file with FNV-1a 64
 * (the same function the Metal backend applies to the renderer's in-memory
 * source text at rhi_shader_create time), and embeds each generated MSL
 * file as a C string (the runtime fallback when engine.metallib is
 * missing; a release build can compile the output with
 * RHI_METAL_SHADER_NO_EMBEDDED_MSL to drop the text).
 *
 * Usage: gen_metal_shader_manifest <shader_dir> <msl_dir> <manifest.lines> <out.c>
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static unsigned long long fnv1a64(const unsigned char *p, size_t len) {
    unsigned long long h = 0xcbf29ce484222325ull;
    while (len-- > 0u) {
        h ^= (unsigned long long)*p++;
        h *= 0x100000001b3ull;
    }
    return h;
}

static char *read_file(const char *path, size_t *out_len) {
    FILE *f = fopen(path, "rb");
    long sz;
    char *buf;
    if (f == NULL) return NULL;
    if (fseek(f, 0, SEEK_END) != 0 || (sz = ftell(f)) < 0 ||
        fseek(f, 0, SEEK_SET) != 0) {
        fclose(f);
        return NULL;
    }
    buf = (char *)malloc((size_t)sz + 1u);
    if (buf == NULL) { fclose(f); return NULL; }
    if (sz > 0 && fread(buf, 1u, (size_t)sz, f) != (size_t)sz) {
        free(buf);
        fclose(f);
        return NULL;
    }
    buf[sz] = '\0';
    fclose(f);
    if (out_len != NULL) *out_len = (size_t)sz;
    return buf;
}

static void emit_c_string(FILE *out, const char *text, size_t len) {
    size_t i;
    fputc('"', out);
    for (i = 0u; i < len; ++i) {
        unsigned char c = (unsigned char)text[i];
        switch (c) {
        case '\\': fputs("\\\\", out); break;
        case '"':  fputs("\\\"", out); break;
        case '\n': fputs("\\n\"\n\"", out); break;   /* line-per-row, readable diff */
        case '\r': break;                            /* drop CR (unix tools emit LF) */
        case '\t': fputs("\\t", out); break;
        default:
            /* Octal (fixed 3 digits): a following [0-9a-f] char can never
             * merge into the escape the way a \xNN sequence could. */
            if (c < 0x20u || c >= 0x7Fu)
                fprintf(out, "\\%03o", (unsigned)c);
            else
                fputc((int)c, out);
        }
    }
    fputs("\"", out);
}

int main(int argc, char **argv) {
    char line[512];
    FILE *lf;
    FILE *out;
    unsigned count = 0u;
    if (argc != 5) {
        fprintf(stderr,
                "usage: gen_metal_shader_manifest <shader_dir> <msl_dir> "
                "<manifest.lines> <out.c>\n");
        return 2;
    }
    lf = fopen(argv[3], "rb");
    if (lf == NULL) {
        fprintf(stderr, "gen_metal_shader_manifest: cannot open %s\n", argv[3]);
        return 1;
    }
    out = fopen(argv[4], "wb");
    if (out == NULL) {
        fprintf(stderr, "gen_metal_shader_manifest: cannot write %s\n", argv[4]);
        fclose(lf);
        return 1;
    }
    fputs("/* GENERATED by engine/tools/gen_metal_shader_manifest.c — do not edit. */\n"
          "#include <rhi/rhi_metal_format.h>\n\n"
          "/* Embedded MSL texts are single logical literals longer than the\n"
          " * ISO C99 4095-char minimum; silence -Woverlength-strings for\n"
          " * this generated file only. */\n"
          "#if defined(__clang__)\n"
          "#pragma clang diagnostic ignored \"-Woverlength-strings\"\n"
          "#elif defined(__GNUC__)\n"
          "#pragma GCC diagnostic ignored \"-Woverlength-strings\"\n"
          "#endif\n\n"
          "const RHIMetalShaderManifestEntry rhi_metal_shader_manifest[] = {\n",
          out);
    /* First pass: the manifest table. */
    while (fgets(line, sizeof(line), lf) != NULL) {
        char base[256], entry[256], path[1024];
        size_t len = 0u;
        char *src;
        unsigned long long h;
        if (sscanf(line, "%255s %255s", base, entry) != 2) continue;
        if (snprintf(path, sizeof(path), "%s/%s", argv[1], base) >=
            (int)sizeof(path)) {
            fprintf(stderr, "path too long: %s\n", base);
            fclose(lf); fclose(out);
            return 1;
        }
        src = read_file(path, &len);
        if (src == NULL) {
            fprintf(stderr, "gen_metal_shader_manifest: missing GLSL %s\n", path);
            fclose(lf); fclose(out);
            return 1;
        }
        h = fnv1a64((const unsigned char *)src, len);
        free(src);
        fprintf(out, "    { 0x%016llxull, \"%s\" },\n", h, entry);
        ++count;
    }
    fputs("};\n\n"
          "const usize rhi_metal_shader_manifest_count =\n"
          "    sizeof(rhi_metal_shader_manifest) /\n"
          "    sizeof(rhi_metal_shader_manifest[0]);\n\n"
          "#ifndef RHI_METAL_SHADER_NO_EMBEDDED_MSL\n"
          "const char *const rhi_metal_shader_msl[] = {\n",
          out);
    /* Second pass: the embedded MSL texts (same order). */
    rewind(lf);
    while (fgets(line, sizeof(line), lf) != NULL) {
        char base[256], entry[256], path[1024];
        size_t len = 0u;
        char *msl;
        if (sscanf(line, "%255s %255s", base, entry) != 2) continue;
        if (snprintf(path, sizeof(path), "%s/%s.metal", argv[2], entry) >=
            (int)sizeof(path)) {
            fprintf(stderr, "path too long: %s\n", entry);
            fclose(lf); fclose(out);
            return 1;
        }
        msl = read_file(path, &len);
        if (msl == NULL) {
            fprintf(stderr, "gen_metal_shader_manifest: missing MSL %s\n", path);
            fclose(lf); fclose(out);
            return 1;
        }
        fputs("    ", out);
        emit_c_string(out, msl, len);
        fputs(",\n", out);
        free(msl);
    }
    fputs("};\n#endif\n", out);
    fclose(lf);
    if (fclose(out) != 0) {
        fprintf(stderr, "gen_metal_shader_manifest: write failed\n");
        return 1;
    }
    printf("gen_metal_shader_manifest: %u entries -> %s\n", count, argv[4]);
    return 0;
}
