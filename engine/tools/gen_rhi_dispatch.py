#!/usr/bin/env python3
"""Generate the committed multi-backend RHI dispatch sources (dev tool only)."""

import argparse
import difflib
from pathlib import Path
import re
import sys


GENERATED_NOTE = "/* Generated by engine/tools/gen_rhi_dispatch.py; do not edit. */"
RUNTIME_OWNED = {"rhi_device_create", "rhi_device_create_compiled"}


def strip_comments(text):
    out = []
    i = 0
    state = "normal"
    while i < len(text):
        c = text[i]
        n = text[i + 1] if i + 1 < len(text) else ""
        if state == "normal":
            if c == "/" and n == "*":
                out.extend("  ")
                i += 2
                state = "block"
                continue
            if c == "/" and n == "/":
                out.extend("  ")
                i += 2
                state = "line"
                continue
            out.append(c)
            if c == '"':
                state = "string"
            elif c == "'":
                state = "char"
            i += 1
            continue
        if state == "block":
            if c == "*" and n == "/":
                out.extend("  ")
                i += 2
                state = "normal"
            else:
                out.append("\n" if c == "\n" else " ")
                i += 1
            continue
        if state == "line":
            out.append(c)
            i += 1
            if c == "\n":
                state = "normal"
            continue
        out.append(c)
        if c == "\\" and n:
            out.append(n)
            i += 2
        else:
            i += 1
            if (state == "string" and c == '"') or (state == "char" and c == "'"):
                state = "normal"
    if state == "block":
        raise ValueError("unterminated block comment")
    return "".join(out)


def normalize(text):
    return " ".join(text.split())


def parse_args(text, api_name):
    text = normalize(text)
    if text in ("", "void"):
        return [], "", ""
    if "..." in text or "(" in text or ")" in text or "[" in text or "]" in text:
        raise ValueError(f"{api_name}: unsupported argument list: {text}")
    args = []
    for arg in text.split(","):
        arg = normalize(arg)
        match = re.fullmatch(r"(.+?)([A-Za-z_]\w*)", arg)
        if not match:
            raise ValueError(f"{api_name}: argument needs a name: {arg}")
        arg_type = match.group(1)
        arg_name = match.group(2)
        if not arg_type or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_ ]*[ *]*", arg_type):
            raise ValueError(f"{api_name}: cannot parse argument type: {arg}")
        args.append((normalize(arg_type), arg_name, arg))
    declarations = ", ".join(arg[2] for arg in args)
    call_args = ", ".join(arg[1] for arg in args)
    return args, declarations, call_args


def parse_declarations(header_text, api_names):
    text = strip_comments(header_text)
    text = re.sub(r"^[ \t]*#.*$", "", text, flags=re.MULTILINE)
    declarations = {}
    for name in api_names:
        candidates = []
        for match in re.finditer(r"\b" + re.escape(name) + r"\s*\(", text):
            start = match.start()
            statement_start = max(
                text.rfind(";", 0, start),
                text.rfind("{", 0, start),
                text.rfind("}", 0, start),
            ) + 1
            return_type = normalize(text[statement_start:start])
            open_paren = text.find("(", start)
            close_paren = text.find(")", open_paren + 1)
            if close_paren == -1:
                continue
            if not text[close_paren + 1:].lstrip().startswith(";"):
                continue
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_ ]*[ *]*", return_type):
                continue
            if return_type.startswith(("return ", "static ", "inline ")):
                continue
            raw_args = text[open_paren + 1:close_paren]
            args, arg_declarations, call_args = parse_args(raw_args, name)
            candidates.append((return_type, args, arg_declarations, call_args))
        if len(candidates) != 1:
            raise ValueError(
                f"{name}: expected exactly one parseable declaration, found {len(candidates)}"
            )
        declarations[name] = candidates[0]
    return declarations


def render_api_h(api_names, declarations):
    lines = [
        GENERATED_NOTE,
        "#ifndef RHI_DISPATCH_RHI_API_H",
        "#define RHI_DISPATCH_RHI_API_H",
        "",
        "#include <rhi/rhi.h>",
        "#include <rhi/rhi_native_vulkan.h>",
        "",
        "typedef struct RHIApi {",
    ]
    for name in api_names:
        return_type, _, args, _ = declarations[name]
        lines.append(f"    {return_type} (*{name})({args});")
    lines.extend([
        "} RHIApi;",
        "",
        "void rhi_dispatch_set_api(const RHIApi *api);",
        "const RHIApi *rhi_api_backend_gl(void);",
        "const RHIApi *rhi_api_backend_vk(void);",
        "",
        "#endif",
        "",
    ])
    return "\n".join(lines)


def render_stub(name, declaration):
    return_type, args, arg_declarations, _ = declaration
    lines = [f"static {return_type} rhi_stub_{name}({arg_declarations}) {{"]
    for _, arg_name, _ in args:
        lines.append(f"    (void){arg_name};")
    lines.append("    rhi_dispatch_stub_log_once();")
    if return_type == "RHIResult":
        lines.append("    return RHI_RESULT_UNAVAILABLE;")
    elif return_type != "void":
        if return_type.endswith("*"):
            lines.append("    return NULL;")
        elif return_type == "bool":
            lines.append("    return false;")
        else:
            lines.append(f"    {return_type} zero = {{0}};")
            lines.append("    return zero;")
    lines.append("}")
    return "\n".join(lines)


def render_forwarder(name, declaration):
    return_type, _, arg_declarations, call_args = declaration
    call = f"rhi_dispatch_active()->{name}({call_args})"
    statement = ";" if return_type == "void" else f"return {call};"
    if return_type == "void":
        statement = f"    {call};"
    else:
        statement = f"    return {call};"
    return f"{return_type} {name}({arg_declarations}) {{\n{statement}\n}}"


def render_dispatch_c(api_names, declarations):
    lines = [
        GENERATED_NOTE,
        '#include "rhi/dispatch/rhi_api.h"',
        '#include "core/log.h"',
        "",
        "#include <stdatomic.h>",
        "",
        "/* The table is swapped on the device-creating thread and read by every",
        " * thread that issues rhi_* calls (e.g. the command-buffer submit thread):",
        " * acquire/release keeps the table contents visible with the pointer. */",
        "static atomic_flag g_stub_logged = ATOMIC_FLAG_INIT;",
        "",
        "static void rhi_dispatch_stub_log_once(void) {",
        "    if (atomic_flag_test_and_set_explicit(&g_stub_logged, memory_order_relaxed)) return;",
        '    LOG_ERROR("RHI call before a device was created");',
        "}",
        "",
    ]
    for name in api_names:
        lines.append(render_stub(name, declarations[name]))
        lines.append("")
    lines.append("static const RHIApi g_stub_api = {")
    for name in api_names:
        lines.append(f"    .{name} = rhi_stub_{name},")
    lines.extend([
        "};",
        "",
        "static _Atomic(const RHIApi *) g_active_api = &g_stub_api;",
        "",
        "void rhi_dispatch_set_api(const RHIApi *api) {",
        "    atomic_store_explicit(&g_active_api, api != NULL ? api : &g_stub_api,",
        "                          memory_order_release);",
        "}",
        "",
        "static inline const RHIApi *rhi_dispatch_active(void) {",
        "    return atomic_load_explicit(&g_active_api, memory_order_acquire);",
        "}",
        "",
        "/* RHI_FORWARDERS_BEGIN */",
    ])
    for index, name in enumerate(api_names):
        if name in RUNTIME_OWNED:
            continue
        lines.append(render_forwarder(name, declarations[name]))
        if index != len(api_names) - 1:
            lines.append("")
    lines.extend(["/* RHI_FORWARDERS_END */", ""])
    return "\n".join(lines)


def render_rename_h(api_names, backend):
    guard = f"RHI_BACKEND_RENAME_{backend.upper()}_H"
    lines = [GENERATED_NOTE, f"#ifndef {guard}", f"#define {guard}", ""]
    for name in api_names:
        lines.append(f"#define {name} rhi_{backend}_{name}")
    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


def render_binding(api_names, backend):
    upper = backend.upper()
    lines = [
        GENERATED_NOTE,
        f"#define RHI_BACKEND_NAMESPACE_{upper} 1",
        '#include "rhi/rhi_backend_namespace.h"',
        '#include "rhi/dispatch/rhi_api.h"',
        "",
        f"const RHIApi *rhi_api_backend_{backend}(void) {{",
        "    static const RHIApi api = {",
    ]
    for name in api_names:
        value = "NULL" if name == "rhi_device_create_compiled" else name
        lines.append(f"        .{name} = {value},")
    lines.extend(["    };", "    return &api;", "}", ""])
    return "\n".join(lines)


def generate(repo_root):
    dispatch_dir = repo_root / "engine/src/rhi/dispatch"
    api_names = [
        line.strip()
        for line in (dispatch_dir / "rhi_backend_api.txt").read_text().splitlines()
        if line.strip()
    ]
    if len(api_names) != len(set(api_names)):
        raise ValueError("rhi_backend_api.txt contains duplicates")
    if not api_names:
        raise ValueError("rhi_backend_api.txt is empty")
    headers = sorted((repo_root / "engine/src/rhi").glob("*.h"))
    if not headers:
        raise ValueError("no RHI headers found")
    header_text = "\n".join(path.read_text() for path in headers)
    declarations = parse_declarations(header_text, api_names)
    return {
        "rhi_api.h": render_api_h(api_names, declarations),
        "rhi_dispatch.c": render_dispatch_c(api_names, declarations),
        "rhi_api_bind_gl.c": render_binding(api_names, "gl"),
        "rhi_api_bind_vk.c": render_binding(api_names, "vk"),
        "rhi_backend_rename_gl.h": render_rename_h(api_names, "gl"),
        "rhi_backend_rename_vk.h": render_rename_h(api_names, "vk"),
    }


def main():
    default_root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=default_root)
    parser.add_argument("--check", action="store_true", help="check committed files without writing")
    args = parser.parse_args()
    repo_root = args.repo_root.resolve()
    dispatch_dir = repo_root / "engine/src/rhi/dispatch"
    try:
        outputs = generate(repo_root)
    except (OSError, ValueError) as error:
        parser.exit(1, f"error: {error}\n")
    if not args.check:
        for filename, content in outputs.items():
            (dispatch_dir / filename).write_text(content)
        print(f"generated {len(outputs)} files in {dispatch_dir}")
        return 0
    failed = False
    for filename, content in outputs.items():
        path = dispatch_dir / filename
        if not path.exists():
            print(f"missing generated file: {path}", file=sys.stderr)
            failed = True
            continue
        actual = path.read_text()
        if actual != content:
            failed = True
            diff = difflib.unified_diff(
                actual.splitlines(True), content.splitlines(True),
                fromfile=str(path), tofile=f"generated/{filename}")
            sys.stdout.writelines(diff)
    if failed:
        return 1
    print("RHI dispatch generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
