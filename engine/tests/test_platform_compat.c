#include "test_framework.h"
#include "platform/platform_compat.h"

static void assert_common(void)
{
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY != 0);
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_NET_LOOP != 0);
}

TEST(host_descriptor)
{
    assert_common();
#if defined(ENGINE_PLATFORM_LINUX)
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_LINUX);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_EPOLL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_GRAPHICS_API, ENGINE_GRAPHICS_API_OPENGL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.native_graphics_api,
              ENGINE_NATIVE_GRAPHICS_API_OPENGL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_VULKAN);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_COMPILED);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_HOST_NATIVE);
#elif defined(ENGINE_PLATFORM_MACOS)
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_MACOS);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_KQUEUE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_HOST_NATIVE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.native_graphics_api,
              ENGINE_NATIVE_GRAPHICS_API_METAL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_METAL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_COMPILED);
#elif defined(ENGINE_PLATFORM_WINDOWS)
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_WINDOWS);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_IOCP);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_HOST_NATIVE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_D3D12);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#elif defined(ENGINE_PLATFORM_QNX)
    /* Host descriptor facts on a real QNX target: poll() net loop, headless
     * surface policy (none required), graphics fail-closed, COMPILED evidence
     * until runtime receipts from target hardware exist. */
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_QNX);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_POLL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_UNAVAILABLE);
    ASSERT_FALSE(ENGINE_PLATFORM_COMPAT_REQUIRES_HOST_SURFACE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_UNAVAILABLE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#endif
}

TEST(descriptor_is_compile_time)
{
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_family,
              ENGINE_PLATFORM_COMPAT_TARGET_FAMILY);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.net_loop, ENGINE_PLATFORM_COMPAT_NET_LOOP);
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY ==
                ENGINE_PLATFORM_COMPAT_TARGET_FAMILY);
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_NET_LOOP == ENGINE_PLATFORM_COMPAT_NET_LOOP);
}

int main(void)
{
    RUN_TEST(host_descriptor);
    RUN_TEST(descriptor_is_compile_time);
    printf("\n=== Results: %d passed, %d failed, %d total ===\n",
           g_test_pass, g_test_fail, g_test_count);
    return g_test_fail > 0 ? 1 : 0;
}
