#include "test_framework.h"
#include "platform/platform_compat.h"

TEST(simulated_descriptor)
{
#if defined(SIMULATE_MACOS)
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_MACOS);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_KQUEUE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_HOST_NATIVE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.native_graphics_api,
              ENGINE_NATIVE_GRAPHICS_API_METAL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_METAL);
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_REQUIRES_HOST_SURFACE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_COMPILED);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#elif defined(SIMULATE_IOS)
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_IOS);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_KQUEUE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_GRAPHICS_API, ENGINE_GRAPHICS_API_COMPILED);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_HOST_NATIVE);
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_REQUIRES_HOST_SURFACE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_HOST_INJECTED);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_METAL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#elif defined(SIMULATE_ANDROID)
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_ANDROID);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_EPOLL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_UNAVAILABLE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_GRAPHICS_API, ENGINE_GRAPHICS_API_NONE);
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_REQUIRES_HOST_SURFACE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_HOST_INJECTED);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_VULKAN);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#elif defined(SIMULATE_HARMONYOS)
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_HARMONYOS);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_EPOLL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_UNAVAILABLE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_GRAPHICS_API, ENGINE_GRAPHICS_API_NONE);
    ASSERT_TRUE(ENGINE_PLATFORM_COMPAT_REQUIRES_HOST_SURFACE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_UNAVAILABLE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_NONE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_NONE);
#elif defined(SIMULATE_QNX)
#if defined(ENGINE_QNX_SCREEN) && defined(ENGINE_VULKAN)
    /* QNX + Screen + explicit Vulkan opt-in: the WSI branch exists
     * (vkCreateScreenSurfaceQNX), so the descriptor advertises the compiled
     * Vulkan path; runtime still needs a target with a Vulkan driver. */
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_QNX);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_POLL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_QNX_SCREEN);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_COMPILED);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_VULKAN);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#elif defined(ENGINE_QNX_SCREEN)
    /* QNX + Screen window layer: the platform creates its own native window
     * (screen_context/screen_window). The default RHI is headless; explicit
     * Vulkan has a separate compiled descriptor, and runtime receipts stay
     * out of this compile-time contract. */
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_QNX);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_POLL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_QNX_SCREEN);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_GRAPHICS_API, ENGINE_GRAPHICS_API_NONE);
    ASSERT_FALSE(ENGINE_PLATFORM_COMPAT_REQUIRES_HOST_SURFACE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.native_graphics_api,
              ENGINE_NATIVE_GRAPHICS_API_NONE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_UNAVAILABLE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_NONE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#else
    /* QNX headless milestone: engine + myui offscreen (dummy PAL) compile and
     * run without a host surface; graphics stays fail-closed until a Screen
     * WSI integration exists, so evidence tops out at COMPILED. */
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_TARGET_FAMILY, ENGINE_TARGET_FAMILY_QNX);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_NET_LOOP, ENGINE_NET_LOOP_POLL);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_SURFACE, ENGINE_SURFACE_UNAVAILABLE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT_GRAPHICS_API, ENGINE_GRAPHICS_API_NONE);
    ASSERT_FALSE(ENGINE_PLATFORM_COMPAT_REQUIRES_HOST_SURFACE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.native_graphics_api,
              ENGINE_NATIVE_GRAPHICS_API_NONE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.vulkan_support,
              ENGINE_VULKAN_SUPPORT_UNAVAILABLE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.target_graphics_api,
              ENGINE_TARGET_GRAPHICS_API_NONE);
    ASSERT_EQ(ENGINE_PLATFORM_COMPAT.support_evidence,
              ENGINE_SUPPORT_EVIDENCE_COMPILED);
#endif
#else
    ASSERT_TRUE(0);
#endif
}

int main(void)
{
    RUN_TEST(simulated_descriptor);
    printf("\n=== Results: %d passed, %d failed, %d total ===\n",
           g_test_pass, g_test_fail, g_test_count);
    return g_test_fail > 0 ? 1 : 0;
}
